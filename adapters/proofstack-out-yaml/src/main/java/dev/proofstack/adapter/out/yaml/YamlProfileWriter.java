package dev.proofstack.adapter.out.yaml;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

import dev.proofstack.core.domain.Area;
import dev.proofstack.core.domain.Education;
import dev.proofstack.core.domain.Evidence;
import dev.proofstack.core.domain.Experience;
import dev.proofstack.core.domain.Lab;
import dev.proofstack.core.domain.Certification;
import dev.proofstack.core.domain.Language;
import dev.proofstack.core.domain.Link;
import dev.proofstack.core.domain.Period;
import dev.proofstack.core.domain.PersonalInfo;
import dev.proofstack.core.domain.Profile;
import dev.proofstack.core.domain.Project;
import dev.proofstack.core.domain.Skill;
import dev.proofstack.core.port.out.ProfileWriter;
import tools.jackson.dataformat.yaml.YAMLFactory;
import tools.jackson.dataformat.yaml.YAMLMapper;
import tools.jackson.dataformat.yaml.YAMLWriteFeature;

/**
 * Driven adapter: serialises a profile to the public {@code profile.yaml} format,
 * in the same field order as the schema so the file reads naturally.
 */
public final class YamlProfileWriter implements ProfileWriter {

    private static final String HEADER = """
            # Generated by Proofstack. Review every TODO before publishing.
            # Schema: schema/profile.schema.json
            """;

    private final YAMLMapper yaml = YAMLMapper.builder(YAMLFactory.builder()
                    .disable(YAMLWriteFeature.WRITE_DOC_START_MARKER)
                    .enable(YAMLWriteFeature.MINIMIZE_QUOTES)
                    .enable(YAMLWriteFeature.ALWAYS_QUOTE_NUMBERS_AS_STRINGS)
                    .enable(YAMLWriteFeature.INDENT_ARRAYS_WITH_INDICATOR)
                    .stringQuotingChecker(TextQuoting.INSTANCE)
                    .build())
            .build();

    @Override
    public void write(Profile profile, Path target, boolean overwrite) {
        if (Files.exists(target) && !overwrite) {
            throw new TargetExistsException(target);
        }
        Map<String, Object> document = document(profile);
        String body = yaml.writeValueAsString(document);
        if (!yaml.valueToTree(document).equals(yaml.readTree(body))) {
            throw new IllegalStateException("the profile could not be written as YAML that reads back the same");
        }
        Path parent = target.toAbsolutePath().getParent();
        Path temp = null;
        try {
            Files.createDirectories(parent);
            // Temporary file and rename: a failure never leaves a half-written profile, and a link to the old
            // file is replaced rather than written through.
            temp = Files.createTempFile(parent, ".profile-", ".yaml.tmp");
            Files.writeString(temp, header(target) + "\n" + body, StandardCharsets.UTF_8);
            try {
                Files.move(temp, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
            } catch (AtomicMoveNotSupportedException e) {
                Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING);
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write " + target, e);
        } finally {
            if (temp != null) {
                try {
                    Files.deleteIfExists(temp);
                } catch (IOException ignored) {
                    // already renamed, or nothing left to clean
                }
            }
        }
    }

    /**
     * Adds a yaml-language-server modeline pointing to the repository schema (relative, so it works in any
     * fork and on any OS) when the target lives inside a Proofstack checkout.
     */
    static String header(Path target) {
        return schemaReference(target)
                .map(ref -> "# yaml-language-server: $schema=" + ref + "\n" + HEADER)
                .orElse(HEADER);
    }

    static java.util.Optional<String> schemaReference(Path target) {
        Path dir = target.toAbsolutePath().normalize().getParent();
        for (Path cursor = dir; cursor != null; cursor = cursor.getParent()) {
            Path schema = cursor.resolve(SCHEMA);
            if (Files.isRegularFile(schema)) {
                return java.util.Optional.of(dir.relativize(schema).toString().replace('\\', '/'));
            }
        }
        return java.util.Optional.empty();
    }

    private static final String SCHEMA = "schema/profile.schema.json";

    static Map<String, Object> document(Profile p) {
        Map<String, Object> doc = new LinkedHashMap<>();
        doc.put("language", p.language());
        doc.put("person", person(p.person()));
        put(doc, "skills", p.skills().stream().map(YamlProfileWriter::skill).toList());
        put(doc, "experience", p.experience().stream().map(YamlProfileWriter::experience).toList());
        put(doc, "education", p.education().stream().map(YamlProfileWriter::education).toList());
        put(doc, "projects", p.projects().stream().map(YamlProfileWriter::project).toList());
        put(doc, "evidence", p.evidence().stream().map(YamlProfileWriter::evidence).toList());
        put(doc, "labs", p.labs().stream().map(YamlProfileWriter::lab).toList());
        put(doc, "languages", p.languages().stream().map(YamlProfileWriter::language).toList());
        put(doc, "certifications", p.certifications().stream().map(YamlProfileWriter::certification).toList());
        return doc;
    }

    private static Map<String, Object> person(PersonalInfo p) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("name", p.name());
        m.put("headline", p.headline());
        put(m, "summary", p.summary());
        put(m, "location", p.location());
        put(m, "email", p.email());
        put(m, "links", links(p.links()));
        return m;
    }

    private static Map<String, Object> skill(Skill s) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("name", s.name());
        m.put("area", lower(s.area()));
        return m;
    }

    private static Map<String, Object> experience(Experience e) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("id", e.id());
        m.put("role", e.role());
        m.put("company", e.company());
        put(m, "location", e.location());
        period(m, e.period());
        if (e.current()) {
            m.put("current", true);
        }
        put(m, "highlights", e.highlights());
        put(m, "technologies", e.technologies());
        put(m, "evidence", e.evidenceIds());
        return m;
    }

    private static Map<String, Object> education(Education e) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("id", e.id());
        m.put("title", e.title());
        m.put("institution", e.institution());
        period(m, e.period());
        put(m, "highlights", e.highlights());
        return m;
    }

    private static Map<String, Object> project(Project p) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("id", p.id());
        m.put("name", p.name());
        m.put("summary", p.summary());
        put(m, "problem", p.problem());
        put(m, "solution", p.solution());
        put(m, "techStack", p.techStack());
        put(m, "learnings", p.learnings());
        put(m, "links", links(p.links()));
        put(m, "areas", p.areas().stream().map(YamlProfileWriter::lower).toList());
        put(m, "evidence", p.evidenceIds());
        return m;
    }

    private static Map<String, Object> evidence(Evidence e) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("id", e.id());
        m.put("category", e.category().name().toLowerCase(Locale.ROOT));
        m.put("title", e.title());
        m.put("context", e.context());
        m.put("action", e.action());
        m.put("result", e.result());
        if (e.link() != null) {
            m.put("link", link(e.link()));
        }
        // Areas equal to the category default are implicit; only write explicit ones.
        if (!e.areas().equals(e.category().defaultAreas())) {
            put(m, "areas", e.areas().stream().map(YamlProfileWriter::lower).toList());
        }
        return m;
    }

    private static Map<String, Object> language(Language l) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("name", l.name());
        put(m, "level", l.level());
        return m;
    }

    private static Map<String, Object> certification(Certification c) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("title", c.title());
        put(m, "issuer", c.issuer());
        if (c.issued() != null) {
            m.put("date", c.issued().toString());
        }
        if (c.link() != null) {
            m.put("link", link(c.link()));
        }
        return m;
    }

    private static Map<String, Object> lab(Lab l) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("id", l.id());
        m.put("name", l.name());
        m.put("type", l.type().name().toLowerCase(Locale.ROOT));
        m.put("description", l.description());
        put(m, "projects", l.projectIds());
        return m;
    }

    private static void period(Map<String, Object> m, Period period) {
        m.put("startDate", period.start().toString());
        period.endDate().ifPresent(end -> m.put("endDate", end.toString()));
    }

    private static List<Map<String, Object>> links(List<Link> links) {
        return links.stream().map(YamlProfileWriter::link).toList();
    }

    private static Map<String, Object> link(Link l) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("label", l.label());
        m.put("url", l.url());
        return m;
    }

    private static String lower(Area area) {
        return area.name().toLowerCase(Locale.ROOT);
    }

    private static void put(Map<String, Object> m, String key, Object value) {
        if (value == null || (value instanceof Collection<?> c && c.isEmpty())) {
            return;
        }
        m.put(key, value);
    }
}
