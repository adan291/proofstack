package dev.proofstack.adapter.out.yaml;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import dev.proofstack.adapter.in.yaml.YamlProfileSource;
import dev.proofstack.core.domain.Profile;
import dev.proofstack.core.port.out.ProfileWriter;

class YamlProfileWriterTest {

    private static final Path REPO = Path.of("../..");

    @TempDir
    Path tmp;

    private final YamlProfileSource reader = new YamlProfileSource();
    private final YamlProfileWriter writer = new YamlProfileWriter();

    @Test
    void roundTripPreservesTheWholeProfile() {
        for (String name : new String[]{"example", "adan"}) {
            Profile original = reader.load(REPO.resolve("profiles/" + name + "/profile.yaml"));
            Path out = tmp.resolve(name + ".yaml");

            writer.write(original, out, false);

            assertThat(reader.load(out)).as(name).isEqualTo(original);
        }
    }

    @Test
    void numberLikeTextsAreWrittenAsText() {
        String[] texts = {"1e3", "2E-5", "+1.5e+10", ".inf", "-.Inf", ".NaN", "1_000", "0o17", "0x1F", "3.14",
                "1.10", "+34", "-1", ".5", "true", "null", "~", "yes", "1:30"};
        Profile example = reader.load(REPO.resolve("profiles/example/profile.yaml"));
        Profile original = new Profile(example.language(), example.person(), example.experience(),
                example.education(), example.projects(),
                java.util.Arrays.stream(texts).map(t -> new dev.proofstack.core.domain.Skill(t,
                        dev.proofstack.core.domain.Area.BACKEND)).toList(),
                example.evidence(), example.labs(), example.languages(), example.certifications());
        Path out = tmp.resolve("profile.yaml");

        writer.write(original, out, false);

        assertThat(reader.load(out)).isEqualTo(original);
    }

    @Test
    void writesReadableYamlWithHeader() throws IOException {
        Profile original = reader.load(REPO.resolve("profiles/example/profile.yaml"));
        Path out = tmp.resolve("nested/dir/profile.yaml");

        writer.write(original, out, false);

        String yaml = Files.readString(out);
        assertThat(yaml).startsWith("# Generated by Proofstack")
                .contains("startDate: 2022-03")
                .contains("area: backend")
                .doesNotContain("---");
    }

    @Test
    void addsRelativeSchemaModelineInsideACheckout() throws IOException {
        Path checkout = tmp.resolve("my-portfolio");
        Files.createDirectories(checkout.resolve("schema"));
        Files.writeString(checkout.resolve("schema/profile.schema.json"), "{}");
        Path out = checkout.resolve("profiles/ada/profile.yaml");

        writer.write(reader.load(REPO.resolve("profiles/example/profile.yaml")), out, false);

        assertThat(Files.readString(out))
                .startsWith("# yaml-language-server: $schema=../../schema/profile.schema.json\n");
        assertThat(YamlProfileWriter.schemaReference(tmp.resolve("elsewhere/profile.yaml"))).isEmpty();
    }

    @Test
    void refusesToOverwriteUnlessAsked() throws IOException {
        Profile original = reader.load(REPO.resolve("profiles/example/profile.yaml"));
        Path out = tmp.resolve("profile.yaml");
        Files.writeString(out, "hand-written");

        assertThatThrownBy(() -> writer.write(original, out, false))
                .isInstanceOf(ProfileWriter.TargetExistsException.class);
        assertThat(Files.readString(out)).isEqualTo("hand-written");

        writer.write(original, out, true);
        assertThat(reader.load(out)).isEqualTo(original);
    }
}
